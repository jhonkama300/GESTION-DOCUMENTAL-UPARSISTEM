// ── Agrupar cargos alfabéticamente (A, B, C, ... 0-9) para usar con Dropdown
//     PrimeReact consume `{ label, items: [{label,value}] }` con optionGroupLabel/Children
//     Deduplicamos antes para evitar keys duplicadas que rompan el render.
function _dedupe(list) {
  const seen = new Set()
  const out = []
  for (const item of list) {
    const key = typeof item === 'string' ? item : item?.nombre
    if (!seen.has(key)) {
      seen.add(key)
      out.push(item)
    }
  }
  return out
}

function _groupByLetter(items, labelFn = (s) => s) {
  const buckets = {}
  for (const item of items) {
    const raw = labelFn(item).trim()
    const ch = raw[0] || '#'
    const key = /[A-Za-zÁÉÍÓÚáéíóúÑñ]/.test(ch) ? ch.toUpperCase() : '#'
    if (!buckets[key]) buckets[key] = []
    buckets[key].push(item)
  }
  return Object.keys(buckets)
    .sort()
    .map((key) => ({
      label: key,
      code: key.toLowerCase(),
      items: buckets[key].map((i) => ({ label: i, value: i })),
    }))
}

export function cargosToDropdownGroups() {
  return _groupByLetter(_dedupe(CARGOS))
}

export function programasToDropdownGroups() {
  const niveles = ['Profesional', 'Tecnólogo', 'Técnico', 'Auxiliar']
  const deduped = _dedupe(PROGRAMAS_ACADEMICOS)
  return niveles
    .map((nivel) => {
      const items = deduped.filter((p) => p.nivel === nivel)
      if (!items.length) return null
      return {
        label: `${nivel} · ${items.length}`,
        code: nivel.toLowerCase(),
        items: items.map((i) => ({ label: i.nombre, value: i.nombre })),
      }
    })
    .filter(Boolean)
}



